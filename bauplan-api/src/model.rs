//! The commit types shared by the endpoints, and the syntax of the names.

use std::collections::BTreeMap;
use std::sync::LazyLock;

use chrono::{DateTime, Utc};
use regex::Regex;
use schemars::JsonSchema;
use serde::{Deserialize, Serialize};

// We refuse the commit syntax (`name@hash`, `~N`, `^N`, `*T`) and a lone
// `-`, so a name never points to a commit, the whitespace, and `$`, which
// can interfere with the name filters.
static REF_NAME: LazyLock<Regex> = LazyLock::new(|| {
    Regex::new(r"^(?:[^@~^*$\s-]|-[^@~^*$\s])[^@~^*$\s]*$").expect("static regex")
});

// URL builders normalize these two names as path navigation rather than data.
pub fn is_ref_name(value: &str) -> bool {
    !matches!(value, "." | "..") && REF_NAME.is_match(value)
}

/// A ref name that follows our syntax.
pub(crate) fn ref_syntax(value: &str, _: &()) -> garde::Result {
    if is_ref_name(value) {
        Ok(())
    } else {
        Err(garde::Error::new("not a valid ref"))
    }
}

/// The name of a namespace or of a table: a SQL identifier, unicode, so we
/// do not support the dot and the dash.
static IDENTIFIER: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"\A\p{L}[\p{L}\p{N}_]*\z").expect("static regex"));

/// The regex has no cap, we stop at 128 chars here.
pub fn is_identifier(value: &str) -> bool {
    value.chars().count() <= 128 && IDENTIFIER.is_match(value)
}

/// Optimistic locking guard for ref mutations.
#[derive(Default, Debug, Serialize, Deserialize, JsonSchema, garde::Validate)]
pub struct ExpectedHead {
    /// Fail unless the ref currently points at this hash.
    #[serde(default)]
    #[garde(skip)]
    pub expected_commit_hash: Option<String>,
}

/// A commit in the catalog history.
#[derive(Debug, Serialize, Deserialize, JsonSchema)]
pub struct Commit {
    /// The commit hash.
    pub hash: String,
    /// The commit title (first line of the message).
    pub title: String,
    /// The full commit message.
    pub message: String,
    /// The author's display name.
    pub author_name: String,
    /// The author's email, if known.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub author_email: Option<String>,
    /// When the commit was authored.
    pub authored_at: DateTime<Utc>,
    /// The committer's display name.
    pub committer_name: String,
    /// The committer's email, if known.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub committer_email: Option<String>,
    /// When the commit was committed.
    pub committed_at: DateTime<Utc>,
    /// The parent commit hash. Absent only on the root commit.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub parent_hash: Option<String>,
    /// The hash of the commit merged in. Present only on merge commits.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub merge_parent_hash: Option<String>,
    /// Arbitrary key-value properties attached to the commit.
    pub properties: BTreeMap<String, String>,
}

/// An object together with the commit that produced the observed state.
#[derive(Debug, Serialize, Deserialize, JsonSchema)]
#[schemars(rename = "{T}WithCommit")]
pub struct WithCommit<T> {
    /// The object.
    #[serde(flatten)]
    pub inner: T,
    /// The commit at which the object was observed or written.
    pub commit: Commit,
}

/// An object together with the hash of the commit it was observed at.
#[derive(Debug, Serialize, Deserialize, JsonSchema)]
#[schemars(rename = "{T}AtCommit")]
pub struct AtCommit<T> {
    /// The object.
    #[serde(flatten)]
    pub inner: T,
    /// The hash of the commit the object was observed at.
    pub commit_hash: String,
}

/// Options attached to any operation that produces a commit.
#[derive(Debug, Default, Serialize, Deserialize, JsonSchema, garde::Validate)]
pub struct CommitOptions {
    /// Free-form body for the commit message; the title is generated by the
    /// server.
    #[serde(default)]
    #[garde(skip)]
    pub body: Option<String>,
    /// Fail with `BRANCH_HEAD_CHANGED` unless the branch head is exactly this
    /// hash.
    #[serde(default)]
    #[garde(skip)]
    pub expected_commit_hash: Option<String>,
}

#[cfg(test)]
mod test {
    use super::*;

    #[test]
    fn identifiers() {
        for valid in [
            "a",
            "A1",
            "bauplan",
            "raw_data",
            "raw_",
            "caffè",
            "日本",
            "Ωmega",
            "данные",
            "a٣",
        ] {
            assert!(is_identifier(valid), "{valid:?}");
        }

        for rejected in [
            "",
            " a",
            "a ",
            "a b",
            "a.b",
            "a/b",
            "big-ns",
            "9raw",
            "_raw",
            "-raw",
            "raw-",
            "cafe\u{301}",
        ] {
            assert!(!is_identifier(rejected), "{rejected:?}");
        }

        assert!(is_identifier(&format!("a{}", "è".repeat(127))));
        assert!(!is_identifier(&format!("a{}", "è".repeat(128))));
    }

    #[test]
    fn ref_names() {
        // We refuse only the commit syntax and the names that URL builders
        // treat as path navigation.
        for valid in [
            "main",
            "big.feature/wip-2",
            "9lead",
            "HEAD",
            "a-b",
            "-main",
            "main-",
        ] {
            assert!(ref_syntax(valid, &()).is_ok(), "{valid:?}");
        }

        for rejected in [
            "",
            "-",
            "main@abc",
            "@abc",
            "main~3",
            "main^2",
            "main*1685185847230",
            "main$",
            "ma$in",
            "my branch",
            " main",
            "main\t",
            ".",
            "..",
        ] {
            assert!(ref_syntax(rejected, &()).is_err(), "{rejected:?}");
        }
    }
}
